/**
 * Embeds the private lead-magnet PDF into the Worker bundle.
 *
 * Source of truth: private_docs/Silver-IRA-Handbook.pdf (never in /public).
 * Output:          lib/generated/handbook-pdf.ts (imported by /api/download-handbook)
 *
 * Runs automatically on every `pnpm build` (local and on Cloudflare CI), because
 * Cloudflare Workers cannot read project files from disk at runtime — only files
 * that were bundled into the Worker. The fs read in the route handler still works
 * in `next dev` / `next start`; this embedded copy is what makes production work.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "private_docs", "Silver-IRA-Handbook.pdf");
const outDir = path.join(root, "lib", "generated");
const out = path.join(outDir, "handbook-pdf.ts");

let base64 = "null";
let bytes = 0;

try {
  const buf = await readFile(src);
  base64 = JSON.stringify(buf.toString("base64"));
  bytes = buf.length;
  console.log(`[embed-handbook] embedded Silver-IRA-Handbook.pdf (${bytes} bytes)`);
} catch {
  console.warn(
    "[embed-handbook] private_docs/Silver-IRA-Handbook.pdf not found — " +
      "/api/download-handbook will return 404 until the PDF is added.",
  );
}

await mkdir(outDir, { recursive: true });
await writeFile(
  out,
  `/* AUTO-GENERATED by scripts/embed-handbook.mjs — do not edit by hand.
 * Source: private_docs/Silver-IRA-Handbook.pdf
 * Ships the PDF inside the Worker bundle so /api/download-handbook can serve it
 * without ever exposing a public static URL.
 */
export const HANDBOOK_PDF_BASE64: string | null = ${base64};
export const HANDBOOK_PDF_BYTES = ${bytes};
`,
  "utf8",
);
