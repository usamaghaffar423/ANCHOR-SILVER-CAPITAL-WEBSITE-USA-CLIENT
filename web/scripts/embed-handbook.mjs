/**
 * Embeds the private lead-magnet PDF into the Worker bundle.
 *
 * Source of truth (never in /public):
 *   private_docs/Silver-IRA-Handbook.pdf → lib/generated/handbook-pdf.ts
 *
 * Runs automatically on every `pnpm build` (local and on Cloudflare CI), because
 * Cloudflare Workers cannot read project files from disk at runtime — only files
 * that were bundled into the Worker. The fs read in each route handler still
 * works in `next dev` / `next start`; these embedded copies are what make
 * production work.
 *
 * A missing PDF is a warning, not a failure: the generated module exports null
 * and the matching route returns 404 until the file is dropped into
 * private_docs/.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const privateDocs = path.join(root, "private_docs");
const outDir = path.join(root, "lib", "generated");

const LEAD_MAGNETS = [
  {
    file: "Silver-IRA-Handbook.pdf",
    out: "handbook-pdf.ts",
    base64Const: "HANDBOOK_PDF_BASE64",
    bytesConst: "HANDBOOK_PDF_BYTES",
    endpoint: "/api/download-handbook",
  },
];

await mkdir(outDir, { recursive: true });

for (const magnet of LEAD_MAGNETS) {
  const src = path.join(privateDocs, magnet.file);
  const out = path.join(outDir, magnet.out);

  let base64 = "null";
  let bytes = 0;

  try {
    const buf = await readFile(src);
    base64 = JSON.stringify(buf.toString("base64"));
    bytes = buf.length;
    console.log(`[embed-lead-magnets] embedded ${magnet.file} (${bytes} bytes)`);
  } catch {
    console.warn(
      `[embed-lead-magnets] private_docs/${magnet.file} not found — ` +
        `${magnet.endpoint} will return 404 until the PDF is added.`,
    );
  }

  await writeFile(
    out,
    `/* AUTO-GENERATED by scripts/embed-handbook.mjs — do not edit by hand.
 * Source: private_docs/${magnet.file}
 * Ships the PDF inside the Worker bundle so ${magnet.endpoint} can serve it
 * without ever exposing a public static URL.
 */
export const ${magnet.base64Const}: string | null = ${base64};
export const ${magnet.bytesConst} = ${bytes};
`,
    "utf8",
  );
}
